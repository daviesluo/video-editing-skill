"""Writes two generated modules from the vendored caption face:

- studio/src/kit/archivo800.ts: the advance width of every character in
  the font, in ems, at weight 800 and normal width (the captions' setting).
  The captions use it to keep every page on one line, so a page never wraps
  and leaves one word alone on a line.
- studio/src/kit/archivoChars.ts: every character the font has. The orphan
  scan reports any visible character outside it ("GLYPH"), because such a
  character falls back to another face and breaks the one-typeface rule.

Re-run it after changing the font or the caption weight:

    python pipeline/fontwidths.py
"""

import json

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

from config import STUDIO, brand

font_file = STUDIO / "public" / brand()["type"]["fontFile"]
font = instancer.instantiateVariableFont(TTFont(font_file), {"wght": 800, "wdth": 100})
upm = font["head"].unitsPerEm
cmap = font.getBestCmap()
chars = [chr(c) for c in sorted(cmap) if c >= 32]
widths = {c: round(font["hmtx"][cmap[ord(c)]][0] / upm, 4) for c in chars}
kit = STUDIO / "src" / "kit"
head = "// Generated by pipeline/fontwidths.py from the vendored caption font. Do not edit by hand.\n"
(kit / "archivo800.ts").write_text(
    head + "// Advance widths in ems of Archivo at weight 800, normal width.\n"
    f"export const EM: Record<string, number> = {json.dumps(widths, ensure_ascii=False, indent=0)};\n")
(kit / "archivoChars.ts").write_text(
    head + "// Every character the vendored face can set.\n"
    f"export const CHARS: string = {json.dumps(''.join(chars), ensure_ascii=False)};\n")
print(kit / "archivo800.ts", len(widths), "characters")
