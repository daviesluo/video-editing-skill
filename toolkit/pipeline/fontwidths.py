"""Writes studio/src/kit/archivo800.ts: the advance width of each character
of the caption face (Archivo at weight 800, normal width), in ems, from the
vendored variable font. The captions use it to keep every page on one line,
so a page never wraps and leaves one word alone on a line. Re-run it after
changing the caption font or weight.

    python pipeline/fontwidths.py
"""

import json

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

from config import STUDIO, brand

font_file = STUDIO / "public" / brand()["type"]["fontFile"]
font = instancer.instantiateVariableFont(TTFont(font_file), {"wght": 800, "wdth": 100})
upm = font["head"].unitsPerEm
cmap = font.getBestCmap()
chars = [chr(c) for c in range(32, 127)] + list("°×≈²³’‘“”−–é¾½¼")
widths = {c: round(font["hmtx"][cmap[ord(c)]][0] / upm, 4) for c in chars if ord(c) in cmap}
out = STUDIO / "src" / "kit" / "archivo800.ts"
body = json.dumps(widths, ensure_ascii=False, indent=0)
out.write_text("// Generated by pipeline/fontwidths.py from the vendored caption font: advance\n"
               "// widths in ems of Archivo at weight 800, normal width. Do not edit by hand.\n"
               f"export const EM: Record<string, number> = {body};\n")
print(out, len(widths), "characters")
